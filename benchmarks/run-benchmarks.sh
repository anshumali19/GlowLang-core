#!/usr/bin/env bash
# Time GlowLang against CPython on the cross-language benchmarks (Linux and
# macOS; benchmarks/run-benchmarks.ps1 is the Windows version).
#
# Runs each benchmark RUNS times with GlowLang and with Python and reports the
# median wall time of the whole process (startup + compile + run). Both
# programs must print the same output, otherwise the row says MISMATCH: a fast
# wrong answer is not a result. Writes a Markdown table to REPORT, so the
# numbers in the docs always come from this script, never from hand edits.
#
#   benchmarks/run-benchmarks.sh [glowlang binary] [python] [runs] [report]
#   benchmarks/run-benchmarks.sh bin/glowlang python3 7 benchmarks/RESULTS-linux.md
#
# GLOW_COMMIT names the commit in the report when the tree is not a git
# checkout (an exported archive, for example).
set -euo pipefail
cd "$(dirname "$0")/.."
BIN=${1:-bin/glowlang}
PY=${2:-python3}
RUNS=${3:-7}
REPORT=${4:-benchmarks/RESULTS-linux.md}

cases=(
  "Fibonacci (sum fib 0..29)|benchmarks/cross/fib"
  "Loop (1M additions)|benchmarks/cross/loop"
  "Ackermann(3, 8)|benchmarks/cross/ack"
  "N-Queens (N=10, objects)|benchmarks/cross/nq"
  "Dijkstra (1000 nodes)|benchmarks/cross/dijkstra"
  "Lists + dict (1M push, 200k keys)|benchmarks/workloads/collections"
  "Strings (200k concat + split)|benchmarks/workloads/strings"
)

now_ms() { date +%s%N | awk '{ printf "%.3f", $1 / 1000000 }'; }

# median_ms OUTFILE CMD...: run CMD $RUNS times; print the median in ms and
# leave the last run's output in OUTFILE.
median_ms() {
  local out=$1; shift
  local times=()
  for ((i = 0; i < RUNS; i++)); do
    local s e
    s=$(now_ms)
    "$@" > "$out" 2>&1
    e=$(now_ms)
    times+=("$(awk -v a="$s" -v b="$e" 'BEGIN { printf "%.3f", b - a }')")
  done
  printf '%s\n' "${times[@]}" | sort -g | awk -v n="$RUNS" 'NR == int(n / 2) + 1 { print; exit }'
}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
rows=()
for c in "${cases[@]}"; do
  name=${c%%|*}; base=${c##*|}
  [ -f "$base.glow" ] && [ -f "$base.py" ] || continue
  g=$(median_ms "$tmp/g.txt" "$BIN" run "$base.glow")
  p=$(median_ms "$tmp/p.txt" "$PY" "$base.py")
  if diff -q <(tr -d '\r' < "$tmp/g.txt") <(tr -d '\r' < "$tmp/p.txt") > /dev/null; then
    ratio=$(awk -v g="$g" -v p="$p" 'BEGIN { printf "%.2fx", p / g }')
  else
    ratio=MISMATCH
  fi
  row=$(awk -v n="$name" -v g="$g" -v p="$p" -v r="$ratio" 'BEGIN { printf "| %s | %.0f ms | %.0f ms | %s |", n, g, p, r }')
  echo "$row"
  rows+=("$row")
done

cpu=$(awk -F': ' '/model name/ { print $2; exit }' /proc/cpuinfo 2>/dev/null || sysctl -n machdep.cpu.brand_string 2>/dev/null || echo unknown)
{
  echo "# Benchmark results (Linux)"
  echo
  echo "Generated by \`benchmarks/run-benchmarks.sh\` (median of $RUNS runs, whole-process wall time including startup)."
  echo
  echo "- Machine: $cpu, $(uname -sr)"
  echo "- GlowLang: \`$BIN\` ($("$BIN" --version 2>/dev/null | head -1), commit ${GLOW_COMMIT:-$(git rev-parse --short HEAD 2>/dev/null || echo unknown)})"
  echo "- Python: $("$PY" --version 2>&1)"
  echo
  echo "| Benchmark | GlowLang | Python | Python time / GlowLang time |"
  echo "|---|---:|---:|---:|"
  printf '%s\n' "${rows[@]}"
  echo
  echo "A value above 1 means GlowLang finished faster. Both languages must print identical output for a row to count."
} > "$REPORT"
echo "Wrote $REPORT"
