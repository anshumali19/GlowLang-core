<#
.SYNOPSIS
  Time GlowLang against CPython on the cross-language benchmarks.

.DESCRIPTION
  Runs each benchmark in benchmarks\cross (and benchmarks\workloads) with
  GlowLang and with Python, -Runs times each, and reports the median wall
  time of the whole process (startup + compile + run). Both programs must
  print the same output, otherwise the row is marked MISMATCH: a fast wrong
  answer is not a result. Writes a Markdown table to -Report so the numbers
  in the docs always come from this script, never from hand edits.

.EXAMPLE
  .\benchmarks\run-benchmarks.ps1 -Binary bin\glowlang.exe
#>
param(
    [string] $Binary = 'bin\glowlang.exe',
    [string] $Python = 'python',
    [int] $Runs = 5,
    [string] $Report = 'benchmarks\RESULTS.md'
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
$exe = (Resolve-Path $Binary).Path

$cases = @(
    @{ Name = 'Fibonacci (sum fib 0..29)'; Glow = 'benchmarks\cross\fib.glow';      Py = 'benchmarks\cross\fib.py' },
    @{ Name = 'Loop (1M additions)';        Glow = 'benchmarks\cross\loop.glow';     Py = 'benchmarks\cross\loop.py' },
    @{ Name = 'Ackermann(3, 8)';            Glow = 'benchmarks\cross\ack.glow';      Py = 'benchmarks\cross\ack.py' },
    @{ Name = 'N-Queens (N=10, objects)';   Glow = 'benchmarks\cross\nq.glow';       Py = 'benchmarks\cross\nq.py' },
    @{ Name = 'Dijkstra (1000 nodes)';      Glow = 'benchmarks\cross\dijkstra.glow'; Py = 'benchmarks\cross\dijkstra.py' },
    @{ Name = 'Lists + dict (1M push, 200k keys)'; Glow = 'benchmarks\workloads\collections.glow'; Py = 'benchmarks\workloads\collections.py' },
    @{ Name = 'Strings (200k concat + split)'; Glow = 'benchmarks\workloads\strings.glow'; Py = 'benchmarks\workloads\strings.py' }
)

function Measure-Run([string]$file, [string]$cmd, [string[]]$argv) {
    $times = @(); $out = $null
    for ($i = 0; $i -lt $Runs; $i++) {
        $sw = [Diagnostics.Stopwatch]::StartNew()
        $o = & $cmd @argv 2>&1 | Out-String
        $sw.Stop()
        if ($LASTEXITCODE -ne 0) { throw "$cmd $argv exited with $LASTEXITCODE`n$o" }
        $times += $sw.Elapsed.TotalMilliseconds
        $out = $o.Trim()
    }
    $sorted = $times | Sort-Object
    return @{ Median = $sorted[[int][Math]::Floor($sorted.Count / 2)]; Output = $out }
}

$rows = @()
foreach ($c in $cases) {
    if (-not (Test-Path $c.Glow) -or -not (Test-Path $c.Py)) { continue }
    $g = Measure-Run $c.Glow $exe @('run', $c.Glow)
    $p = Measure-Run $c.Py $Python @($c.Py)
    $same = ($g.Output -replace "`r", '') -eq ($p.Output -replace "`r", '')
    $ratio = $p.Median / $g.Median
    $rows += [pscustomobject]@{
        Benchmark = $c.Name
        GlowLang  = ('{0:N0} ms' -f $g.Median)
        Python    = ('{0:N0} ms' -f $p.Median)
        Speedup   = if ($same) { ('{0:N2}x' -f $ratio) } else { 'MISMATCH' }
    }
}
$rows | Format-Table -AutoSize | Out-String | Write-Host

$pyVer = (& $Python --version 2>&1) -join ' '
$cpu = (Get-CimInstance Win32_Processor | Select-Object -First 1).Name.Trim()
$commit = (git rev-parse --short HEAD 2>$null)
$md = @("# Benchmark results", "",
        "Generated by ``benchmarks/run-benchmarks.ps1`` (median of $Runs runs, whole-process wall time including startup).",
        "", "- Machine: $cpu", "- GlowLang: ``$Binary`` (commit $commit + working tree)", "- Python: $pyVer", "",
        "| Benchmark | GlowLang | Python | Python time / GlowLang time |", "|---|---:|---:|---:|")
foreach ($r in $rows) { $md += "| $($r.Benchmark) | $($r.GlowLang) | $($r.Python) | $($r.Speedup) |" }
$md += ""
$md += "A value above 1 means GlowLang finished faster. Both languages must print identical output for a row to count."
Set-Content -Path $Report -Value $md -Encoding utf8
Write-Host "Wrote $Report"
