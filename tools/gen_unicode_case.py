"""Generate src/unicode_case.h: the Unicode case mappings behind
text.upper() and text.lower().

Run with any Python 3 (its Unicode database is the source):
    python tools/gen_unicode_case.py

One-to-one mappings are stored as runs (lo, hi, delta, stride): every
code point lo, lo+stride, ... up to hi maps to itself plus delta. Mappings
to several characters (German sharp s upper-cases to "SS") are listed
one by one. Context-dependent rules (Greek final sigma, Turkish dotless i)
are not applied, as in a locale-independent simple case mapping.
"""
import os
import sys
import unicodedata

def runs(pairs):
    """[(cp, target)] sorted by cp -> [(lo, hi, delta, stride)]."""
    out = []
    for cp, t in pairs:
        d = t - cp
        if out:
            lo, hi, delta, stride = out[-1]
            step = cp - hi
            if delta == d and (stride == step or (lo == hi and step in (1, 2))):
                out[-1] = (lo, cp, delta, step if lo == hi else stride)
                continue
        out.append((cp, cp, d, 1))
    return out

def table(direction):
    single, multi = [], []
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        m = ch.upper() if direction == "upper" else ch.lower()
        if m == ch:
            continue
        if len(m) == 1:
            single.append((cp, ord(m)))
        else:
            multi.append((cp, m))
    return runs(single), multi

LOOKUP = r"""
/* Case mapping of cp (upper != 0: upper case). Returns the single mapped
   code point, or cp itself when it has no mapping; *multi is set (and the
   return value is -1) when the mapping is several characters. */
static inline int32_t unicode_case_map(int upper, int32_t cp, const char **multi) {
    const UnicodeCaseRun *t = upper ? unicode_upper_runs : unicode_lower_runs;
    int n = upper ? (int)(sizeof(unicode_upper_runs) / sizeof(*t)) : (int)(sizeof(unicode_lower_runs) / sizeof(*t));
    const UnicodeCaseMulti *m = upper ? unicode_upper_multi : unicode_lower_multi;
    int nm = upper ? (int)(sizeof(unicode_upper_multi) / sizeof(*m)) : (int)(sizeof(unicode_lower_multi) / sizeof(*m));
    *multi = 0;
    int lo = 0, hi = n - 1, best = -1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (t[mid].lo <= cp) { best = mid; lo = mid + 1; } else hi = mid - 1;
    }
    /* Runs with stride 2 can interleave, so look a few runs back. */
    for (int i = best; i >= 0 && i > best - 8; i--)
        if (cp <= t[i].hi && (cp - t[i].lo) % t[i].stride == 0) return cp + t[i].delta;
    lo = 0; hi = nm - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (m[mid].cp == cp) { *multi = m[mid].to; return -1; }
        if (m[mid].cp < cp) lo = mid + 1; else hi = mid - 1;
    }
    return cp;
}
"""

def c_bytes(s):
    return '"' + "".join("\\x%02x" % b for b in s.encode("utf-8")) + '"'

def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = []
    out.append("/* Generated by tools/gen_unicode_case.py from the Unicode %s database"
               % unicodedata.unidata_version)
    out.append("   (Python %d.%d). Do not edit by hand. */" % sys.version_info[:2])
    out.append("#ifndef GLOWLANG_UNICODE_CASE_H")
    out.append("#define GLOWLANG_UNICODE_CASE_H")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("/* lo, hi, delta, stride: lo, lo+stride, ... <= hi map to cp + delta. */")
    out.append("typedef struct { int32_t lo, hi, delta, stride; } UnicodeCaseRun;")
    out.append("/* A code point whose mapping is several characters (UTF-8). */")
    out.append("typedef struct { int32_t cp; const char *to; } UnicodeCaseMulti;")
    for direction in ("upper", "lower"):
        single, multi = table(direction)
        out.append("")
        out.append("static const UnicodeCaseRun unicode_%s_runs[] = {" % direction)
        for lo, hi, d, st in single:
            out.append("    {0x%04X, 0x%04X, %d, %d}," % (lo, hi, d, st))
        out.append("};")
        out.append("static const UnicodeCaseMulti unicode_%s_multi[] = {" % direction)
        for cp, m in multi:
            out.append("    {0x%04X, %s}," % (cp, c_bytes(m)))
        out.append("};")
    out.append(LOOKUP)
    out.append("#endif")
    path = os.path.join(root, "src", "unicode_case.h")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path)

if __name__ == "__main__":
    main()
